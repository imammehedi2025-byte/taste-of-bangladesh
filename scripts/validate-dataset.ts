/**
 * Dataset validator. Run with: npm run validate:data
 * Exits non-zero on any error and writes docs/VALIDATION_REPORT.md.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { DIVISIONS } from '../src/data/divisions';
import { DISTRICTS, DISTRICT_BY_ID } from '../src/data/districts';
import { FOODS } from '../src/data/foods';
import { SOURCES } from '../src/data/sources';

const errors: string[] = [];
const expectedCounts: Record<string, number> = {
  dhaka: 13, chattogram: 11, rajshahi: 8, khulna: 10, barishal: 6, sylhet: 4, rangpur: 8, mymensingh: 4,
};

// 1. District registry
if (DISTRICTS.length !== 64) errors.push(`Expected 64 districts, found ${DISTRICTS.length}`);
const ids = new Set<string>();
const names = new Set<string>();
for (const d of DISTRICTS) {
  if (ids.has(d.id)) errors.push(`Duplicate district id ${d.id}`);
  if (names.has(d.nameEn)) errors.push(`Duplicate district name ${d.nameEn}`);
  ids.add(d.id);
  names.add(d.nameEn);
  if (!DIVISIONS.find((v) => v.id === d.divisionId)) errors.push(`District ${d.id} has unknown division`);
}
for (const [div, n] of Object.entries(expectedCounts)) {
  const got = DISTRICTS.filter((d) => d.divisionId === div).length;
  if (got !== n) errors.push(`Division ${div}: expected ${n} districts, found ${got}`);
}

// 2. Foods
const foodIds = new Set<string>();
const sourceMap = SOURCES as Record<string, { independentGroup: string }>;
for (const food of FOODS) {
  if (foodIds.has(food.id)) errors.push(`Duplicate food id ${food.id}`);
  foodIds.add(food.id);
  const d = DISTRICT_BY_ID[food.districtId];
  if (!d) errors.push(`${food.id}: unknown district`);
  else if (d.divisionId !== food.divisionId) errors.push(`${food.id}: division mismatch`);
  if (!food.nameEn || !food.nameBn) errors.push(`${food.id}: missing name`);
  if (!/[ঀ-৿]/.test(food.nameBn)) errors.push(`${food.id}: Bangla name has no Bangla script`);
  if (food.sources.length === 0) errors.push(`${food.id}: no sources`);
  for (const s of food.sources) if (!sourceMap[s]) errors.push(`${food.id}: unknown source ${s}`);

  const groups = new Set(food.sources.map((s) => sourceMap[s]?.independentGroup));
  if (food.evidenceLevel === 'gi') {
    if (!food.sources.includes('dpdt') || !food.giNumber) errors.push(`${food.id}: GI level without DPDT source/number`);
  }
  if (food.evidenceLevel === 'multi' && groups.size < 2)
    errors.push(`${food.id}: 'multi' needs ≥2 independent source groups, has ${groups.size}`);
  if (food.evidenceLevel === 'single' && groups.size > 1)
    errors.push(`${food.id}: marked single but has ${groups.size} independent groups — upgrade or explain`);
  const expectedStatus = food.evidenceLevel === 'gi' || food.evidenceLevel === 'multi' ? 'Verified' : 'Needs Review';
  if (food.status !== expectedStatus) errors.push(`${food.id}: status ${food.status} ≠ ${expectedStatus}`);
}

// 3. Coverage
const perDistrict = DISTRICTS.map((d) => {
  const list = FOODS.filter((x) => x.districtId === d.id);
  return { d, total: list.length, verified: list.filter((x) => x.status === 'Verified').length };
});
for (const row of perDistrict) if (row.total === 0) errors.push(`District ${row.d.id} has no foods`);

// 4. Report
const verified = FOODS.filter((x) => x.status === 'Verified').length;
const gi = FOODS.filter((x) => x.evidenceLevel === 'gi').length;
const noVerified = perDistrict.filter((r) => r.verified === 0);
const lines = [
  '# Dataset Validation Report',
  '',
  `Generated by \`npm run validate:data\` on ${new Date().toISOString().slice(0, 10)}.`,
  '',
  `- Districts: **${DISTRICTS.length}** (unique ids: ${ids.size})`,
  `- Divisions: ${DIVISIONS.map((v) => `${v.nameEn} ${DISTRICTS.filter((d) => d.divisionId === v.id).length}`).join(' · ')}`,
  `- Foods: **${FOODS.length}** — Verified ${verified} (of which DPDT GI ${gi}), Needs Review ${FOODS.length - verified}`,
  `- Districts with at least one food: ${perDistrict.filter((r) => r.total > 0).length} / 64`,
  `- Districts with at least one Verified food: ${64 - noVerified.length} / 64`,
  `- Errors: ${errors.length === 0 ? 'none' : errors.length}`,
  '',
  '## Districts with no Verified food yet (need local research)',
  '',
  ...(noVerified.length ? noVerified.map((r) => `- ${r.d.nameEn} (${r.d.nameBn}) — ${r.total} candidate(s), all Needs Review`) : ['- none']),
  '',
  '## Per-district coverage',
  '',
  '| District | Division | Foods | Verified |',
  '|---|---|---|---|',
  ...perDistrict.map((r) => `| ${r.d.nameEn} | ${r.d.divisionId} | ${r.total} | ${r.verified} |`),
  '',
  ...(errors.length ? ['## Errors', '', ...errors.map((e) => `- ${e}`)] : []),
];
mkdirSync('docs', { recursive: true });
writeFileSync('docs/VALIDATION_REPORT.md', lines.join('\n') + '\n');

console.log(lines.slice(0, 11).join('\n'));
if (errors.length) {
  console.error('\nERRORS:\n' + errors.join('\n'));
  process.exit(1);
}
console.log('\n✓ Dataset valid');
